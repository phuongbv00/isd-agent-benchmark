#!/usr/bin/env python3
"""Generate the RQ2 encoder-sensitivity table, macros and stats dump.

Reads ``pooled["alignment_sensitivity"]`` (written by
07_pool_ladder_runs.py --encoders/--auto-encoders) and writes into
``results/generated/``:

  tab_sensitivity.tex   booktabs table: rows = encoders, per size the proposed
                        agent's mean alignment, the rank correlation with the
                        primary encoder, and the proposed agent's rank.
  sens_macros.tex       \\newcommand macros for every headline number, so the
                        "ranking survives an encoder swap" claim in the prose
                        is generated rather than typed.
  stats_sensitivity.md  human-readable dump (per size x encoder: rho, tau-b,
                        exact p, top-1, sign/Holm agreement, coverage).

Separate from 09_gen_paper_tables.py on purpose: the sweep has its own macro
namespace and its own audience, exactly like the ablation's
ablation/11_gen_ablation_tables.py. Formatters and size words are imported
from 09 rather than copied.

Usage:
  python scripts/alignmentgraph-isd-bench/14_gen_sensitivity_table.py
  python scripts/alignmentgraph-isd-bench/14_gen_sensitivity_table.py \
      --pooled results/pooled_ladder.json --outdir results/generated
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import math
import sys
from datetime import datetime
from pathlib import Path

BENCH_ROOT = Path(__file__).resolve().parents[2]  # isd-agent-benchmark/


def _load(name: str, mod_name: str):
    """Import a digit-prefixed sibling script."""
    path = Path(__file__).resolve().with_name(name)
    spec = importlib.util.spec_from_file_location(mod_name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module   # @dataclass resolves via sys.modules
    spec.loader.exec_module(module)
    return module


TAB = _load("09_gen_paper_tables.py", "_tables")
fmt_vn, fmt_p = TAB.fmt_vn, TAB.fmt_p
size_word, size_display, size_of_label = TAB.size_word, TAB.size_display, TAB.size_of_label

#: Display names for the sensitivity design (guides section 8). Unknown keys
#: (ad-hoc arms) fall back to the key itself.
ENCODER_DISPLAY = {
    "nemotron": "E1 Nemotron-8B",
    "bgem3": "E2 bge-m3",
    "granite": "E3 granite-311m",
    "tfidf": "E4 TF-IDF",
}

#: LaTeX macro names cannot contain digits, so every encoder key needs a word.
ENCODER_WORDS = {
    "nemotron": "Nemotron",
    "bgem3": "BgeMThree",
    "granite": "Granite",
    "tfidf": "Tfidf",
}

_DIGIT_WORDS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
                "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}


def encoder_word(key: str) -> str:
    """Digit-free CamelCase token for a macro name."""
    if key in ENCODER_WORDS:
        return ENCODER_WORDS[key]
    out = []
    for part in "".join(c if c.isalnum() else " " for c in key).split():
        out.append("".join(_DIGIT_WORDS.get(c, c) for c in part).capitalize())
    return "".join(out) or "Arm"


def header_comment(pooled: dict, what: str) -> str:
    return "\n".join([
        "% AUTO-GENERATED by isd-agent-benchmark/scripts/alignmentgraph-isd-bench/"
        "14_gen_sensitivity_table.py — DO NOT EDIT BY HAND",
        f"% {what}",
        f"% generated_at: {datetime.now().isoformat(timespec='seconds')}",
        f"% source pooled JSON generated_at: {pooled.get('generated_at', '?')}",
        "",
    ])


# ── data access ──────────────────────────────────────────────────────────────

def arm_rows(pooled: dict) -> list[dict]:
    """One row per encoder, primary first, each with per-size cells.

    The primary is included as the reference row: it is what the arms are
    compared against, so leaving it out would make the table unreadable. Its
    rho column is '--' (an encoder cannot disagree with itself).
    """
    sens = pooled["alignment_sensitivity"]
    metric = sens["metric"]
    proposed = pooled["config"]["proposed"]
    baselines = pooled["config"]["baselines"]
    labels = [m["label"] for m in pooled["models"]]

    def cells_from(models_map: dict, agree_rows: dict | None) -> dict:
        cells = {}
        for label in labels:
            agents = (models_map or {}).get(label) or {}
            means = {a: agents.get(a, {}).get(metric, {}).get("mean")
                     for a in [proposed] + baselines}
            means = {a: v for a, v in means.items() if v is not None}
            best_b = max((b for b in baselines if b in means),
                         key=lambda b: means[b], default=None)
            row = (agree_rows or {}).get(label) or {}
            cells[label] = {
                "mean": means.get(proposed),
                "delta_best": (means[proposed] - means[best_b]
                               if best_b and proposed in means else None),
                "best_baseline": best_b,
                "rho": row.get("spearman_rho_agent_means"),
                "tau": row.get("kendall_tau_b_agent_means"),
                "p_exact": row.get("spearman_p_exact"),
                "rank": row.get("proposed_rank_here"),
                "top1": row.get("top1_agent_here"),
                "top1_same": (row.get("top1_agent_here") == row.get("top1_agent_primary")
                              if row.get("top1_agent_here") else None),
                "scen_rho": row.get("spearman_rho_scenario_level_proposed"),
                "sign": row.get("sign_agreement_vs_baselines"),
                "p_holm_max": None,     # filled by the caller from that arm's stats
            }
        return cells

    rows = []
    primary_align = pooled.get("alignment")
    if primary_align:
        primary_ranks = _primary_ranks(primary_align, labels, metric,
                                       [proposed] + baselines, proposed)
        cells = cells_from(primary_align.get("models"), None)
        for label in labels:
            cells[label]["rank"] = primary_ranks.get(label)
            cells[label]["p_holm_max"] = _holm_max(primary_align, label)
        rows.append({"key": sens["primary_encoder"], "is_primary": True,
                     "label_text": ENCODER_DISPLAY.get(sens["primary_encoder"],
                                                       sens["primary_encoder"]),
                     "encoder_label": primary_align.get("encoder_label"),
                     "coverage": primary_align.get("n_scenario_files"),
                     "cells": cells})
    for entry in sens["encoders"]:
        if "skipped" in entry:
            rows.append({"key": entry["key"], "is_primary": False,
                         "label_text": ENCODER_DISPLAY.get(entry["key"], entry["key"]),
                         "skipped": entry["skipped"], "cells": {}})
            continue
        agree = {r["label"]: r
                 for r in entry["agreement_with_primary"].get("per_model") or []}
        cells = cells_from(entry.get("models"), agree)
        for label in labels:
            cells[label]["p_holm_max"] = _holm_max(entry, label)
        rows.append({"key": entry["key"], "is_primary": False,
                     "label_text": ENCODER_DISPLAY.get(entry["key"], entry["key"]),
                     "encoder_label": entry.get("encoder_label"),
                     "coverage": (entry.get("coverage") or {}).get("n_scenario_files"),
                     "cells": cells})
    return rows


def _primary_ranks(align: dict, labels: list[str], metric: str,
                   agents: list[str], proposed: str) -> dict[str, int | None]:
    out = {}
    for label in labels:
        per_agent = (align.get("models") or {}).get(label) or {}
        means = {a: per_agent.get(a, {}).get(metric, {}).get("mean")
                 for a in agents}
        means = {a: v for a, v in means.items() if v is not None}
        out[label] = (sorted(means, key=lambda a: -means[a]).index(proposed) + 1
                      if proposed in means else None)
    return out


def _holm_max(pooled_align: dict, label: str) -> float | None:
    """Worst Holm-corrected p among that size's paired comparisons."""
    for entry in (pooled_align.get("stats") or {}).get("per_model") or []:
        if entry.get("label") == label:
            ps = [r["p_holm"] for r in entry.get("comparisons") or [] if "p_holm" in r]
            return max(ps) if ps else None
    return None


# ── tab_sensitivity.tex ──────────────────────────────────────────────────────

def gen_table(pooled: dict, rows: list[dict]) -> str:
    labels = [m["label"] for m in pooled["models"]]
    proposed_disp = TAB.AGENT_DISPLAY.get(pooled["config"]["proposed"],
                                          pooled["config"]["proposed"])
    colspec = "@{}l" + "r@{\\hskip 3pt}r@{\\hskip 3pt}c" * len(labels) + "@{}"
    head = [
        header_comment(pooled, "RQ2 encoder sensitivity: alignment level, rank "
                               "agreement with the primary encoder, and the "
                               "proposed agent's rank, per model size."),
        "\\begin{table*}[t]",
        "\\centering",
        "\\small",
        "\\begin{tabular}{" + colspec + "}",
        "\\toprule",
        "Encoder & " + " & ".join(
            f"\\multicolumn{{3}}{{c}}{{Qwen3.5-{size_display(lb)}}}" for lb in labels
        ) + " \\\\",
        " ".join(f"\\cmidrule(lr){{{2 + 3 * i}-{4 + 3 * i}}}"
                 for i in range(len(labels))),
        " & " + " & ".join("Align & $\\rho$ & h" for _ in labels) + " \\\\",
        "\\midrule",
    ]
    body = []
    for row in rows:
        name = row["label_text"]
        if row.get("is_primary"):
            name = f"\\textbf{{{name}}} (primary)"
        if "skipped" in row:
            body.append(f"{name} & " + " & ".join(
                "\\multicolumn{3}{c}{--}" for _ in labels) + " \\\\")
            continue
        cells = []
        for label in labels:
            c = row["cells"].get(label, {})
            align = fmt_vn(c.get("mean"), 3) if c.get("mean") is not None else "--"
            if row.get("is_primary"):
                rho = "--"
            else:
                rho = fmt_vn(c["rho"], 3) if isinstance(c.get("rho"), float) else "--"
            rank = str(c["rank"]) if c.get("rank") else "--"
            cells += [align, rho, rank]
        body.append(f"{name} & " + " & ".join(cells) + " \\\\")
    tail = [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Độ nhạy theo encoder của endpoint RQ2 (objective--assessment "
        "alignment). Cùng một tập run được chấm lại bằng từng encoder; "
        "\\emph{Align} = trung bình của " + proposed_disp + ", "
        "$\\rho$ = tương quan hạng Spearman của vector điểm trung bình theo agent "
        "so với encoder chính, \\emph{h} = hạng của " + proposed_disp + " trong "
        "cỡ mô hình đó. Giao thức đo là như nhau ở mọi hàng --- chỉ encoder đổi.}",
        "\\label{tab:rq2-sensitivity}",
        "\\end{table*}",
    ]
    return "\n".join(head + body + tail) + "\n"


# ── sens_macros.tex ──────────────────────────────────────────────────────────

def gen_macros(pooled: dict, rows: list[dict]) -> str:
    sens = pooled["alignment_sensitivity"]
    labels = [m["label"] for m in pooled["models"]]
    tex = [header_comment(pooled, "RQ2 encoder-sensitivity macros.")]

    def newcmd(name: str, value: str, desc: str) -> None:
        tex.append(f"\\newcommand{{\\{name}}}{{{value}}}  % {desc}")

    summary = sens["summary"]
    newcmd("rqTwoSensNumEncoders", str(summary["n_encoders"] + 1),
           "encoders compared, including the primary")
    newcmd("rqTwoSensPrimaryName",
           ENCODER_DISPLAY.get(sens["primary_encoder"], sens["primary_encoder"]),
           "primary encoder display name")
    for key, macro, desc in (
        ("min_spearman_rho_any_encoder_any_size", "rqTwoSensRhoMinAll",
         "min Spearman rho over every encoder x size cell"),
        ("min_kendall_tau_b_any_encoder_any_size", "rqTwoSensTauMinAll",
         "min Kendall tau-b over every encoder x size cell"),
    ):
        val = summary.get(key)
        newcmd(macro, fmt_vn(val, 3) if isinstance(val, float) else "--", desc)
    p_max = summary.get("max_p_holm_any_encoder_any_size")
    newcmd("rqTwoSensPHolmMaxAll", fmt_p(p_max) if p_max is not None else "--",
           "worst Holm-corrected p anywhere in the sweep")
    newcmd("rqTwoSensTopOneCells",
           f"{summary['n_cells_proposed_ranks_first']}/{summary['n_cells']}",
           "cells where the proposed agent ranks first (arms only)")

    for row in rows:
        if "skipped" in row:
            continue
        w = encoder_word(row["key"])
        rhos = [c["rho"] for c in row["cells"].values()
                if isinstance(c.get("rho"), float) and not math.isnan(c["rho"])]
        if rhos:
            newcmd(f"rqTwoSensRhoMin{w}", fmt_vn(min(rhos), 3),
                   f"min rho vs primary across sizes ({row['key']})")
        holms = [c["p_holm_max"] for c in row["cells"].values()
                 if c.get("p_holm_max") is not None]
        if holms:
            newcmd(f"rqTwoSensPHolmMax{w}", fmt_p(max(holms)),
                   f"worst Holm p across sizes under {row['key']}")
        for i, label in enumerate(labels):
            c = row["cells"].get(label) or {}
            sw = size_word(label, i)
            if c.get("mean") is not None:
                newcmd(f"rqTwoSensAlign{w}{sw}", fmt_vn(c["mean"], 3),
                       f"proposed mean alignment @ {label} ({row['key']})")
            if c.get("delta_best") is not None:
                newcmd(f"rqTwoSensDeltaBest{w}{sw}", fmt_vn(c["delta_best"], 3),
                       f"proposed - best baseline @ {label} ({row['key']})")
            if isinstance(c.get("rho"), float) and not math.isnan(c["rho"]):
                newcmd(f"rqTwoSensRho{w}{sw}", fmt_vn(c["rho"], 3),
                       f"Spearman rho vs primary @ {label} ({row['key']})")
            if isinstance(c.get("tau"), float) and not math.isnan(c["tau"]):
                newcmd(f"rqTwoSensTau{w}{sw}", fmt_vn(c["tau"], 3),
                       f"Kendall tau-b vs primary @ {label} ({row['key']})")
    return "\n".join(tex) + "\n"


# ── stats_sensitivity.md ─────────────────────────────────────────────────────

def gen_stats_md(pooled: dict, rows: list[dict]) -> str:
    sens = pooled["alignment_sensitivity"]
    labels = [m["label"] for m in pooled["models"]]
    out = [
        "<!-- AUTO-GENERATED by isd-agent-benchmark/scripts/alignmentgraph-isd-bench/"
        "14_gen_sensitivity_table.py — DO NOT EDIT BY HAND -->",
        "# RQ2 encoder sensitivity",
        "",
        f"- source pooled JSON generated_at: `{pooled.get('generated_at', '?')}`",
        f"- primary encoder: `{sens['primary_encoder']}` (owns `alignment_scores.json`)",
        f"- metric: `{sens['metric']}`",
        f"- {sens['definition']}",
        "",
    ]
    for row in rows:
        if "skipped" in row:
            out += [f"## {row['label_text']} — SKIPPED", "", f"{row['skipped']}", ""]
            continue
        tag = " (primary)" if row.get("is_primary") else ""
        out += [
            f"## {row['label_text']}{tag}",
            "",
            f"- encoder label in the artifacts: `{row.get('encoder_label')}`",
            f"- coverage: {row.get('coverage')} scenario score file(s)",
            "",
            "| Size | proposed align | Δ vs best baseline | rank | ρ vs primary | "
            "τ-b | exact p | top-1 | scenario ρ | sign/Holm agree |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for label in labels:
            c = row["cells"].get(label) or {}
            sign = c.get("sign") or {}
            sign_txt = (f"{sign.get('n_same_sign')}/{sign.get('n')} · "
                        f"{sign.get('n_same_holm_verdict_at_05')}/{sign.get('n')}"
                        if sign.get("n") else "--")
            top1 = c.get("top1") or "--"
            if c.get("top1_same") is False:
                top1 += " (DIFFERS)"
            out.append(
                f"| {label} | {_num(c.get('mean'), 3)} | {_num(c.get('delta_best'), 3)} "
                f"| {c.get('rank') or '--'} | {_num(c.get('rho'), 3)} "
                f"| {_num(c.get('tau'), 3)} | {_sci(c.get('p_exact'))} | {top1} "
                f"| {_num(c.get('scen_rho'), 3)} | {sign_txt} |"
            )
        out.append("")
    s = sens["summary"]
    out += [
        "## Headline",
        "",
        f"- encoders pooled as arms: {s['n_encoders']} (skipped: {s['n_skipped']})",
        f"- min Spearman ρ over every encoder × size: {_num(s.get('min_spearman_rho_any_encoder_any_size'), 3)}",
        f"- min Kendall τ-b: {_num(s.get('min_kendall_tau_b_any_encoder_any_size'), 3)}",
        f"- top-1 agent identical in every cell: {s.get('top1_stable_all_encoders_all_sizes')}",
        f"- proposed agent ranks first in {s['n_cells_proposed_ranks_first']}/{s['n_cells']} arm cells",
        f"- worst Holm-corrected p anywhere in the sweep: {_sci(s.get('max_p_holm_any_encoder_any_size'))}",
        "",
        "Sign/Holm agree = of the paired proposed-vs-baseline comparisons at that "
        "size, how many keep the same sign, and how many keep the same "
        "significant/not verdict at α=0.05, when the encoder is swapped.",
        "",
    ]
    return "\n".join(out)


def _num(x, nd: int = 3) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    return f"{x:.{nd}f}"


def _sci(p) -> str:
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "--"
    return f"{p:.2e}"


# ── main ─────────────────────────────────────────────────────────────────────

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate the RQ2 encoder-sensitivity table, macros and stats dump.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--pooled", type=Path,
                        default=BENCH_ROOT / "results" / "pooled_ladder.json")
    parser.add_argument("--outdir", type=Path,
                        default=BENCH_ROOT / "results" / "generated")
    args = parser.parse_args()

    if not args.pooled.exists():
        print(f"ERROR: {args.pooled} not found — run 07_pool_ladder_runs.py first.",
              file=sys.stderr)
        return 1
    pooled = json.loads(args.pooled.read_text(encoding="utf-8"))
    if not pooled.get("alignment_sensitivity"):
        print(f"ERROR: {args.pooled} has no 'alignment_sensitivity'. Score the sweep "
              "and re-pool:\n"
              "  python scripts/alignmentgraph-isd-bench/06_score_alignment.py "
              "--encoder-presets nemotron,bgem3,granite,tfidf --overwrite <run dirs>\n"
              "  python scripts/alignmentgraph-isd-bench/07_pool_ladder_runs.py "
              "--auto-glob '...' --auto-encoders", file=sys.stderr)
        return 1

    rows = arm_rows(pooled)
    args.outdir.mkdir(parents=True, exist_ok=True)
    for name, text in (
        ("tab_sensitivity.tex", gen_table(pooled, rows)),
        ("sens_macros.tex", gen_macros(pooled, rows)),
        ("stats_sensitivity.md", gen_stats_md(pooled, rows)),
    ):
        (args.outdir / name).write_text(text, encoding="utf-8")
        print(f"wrote {args.outdir / name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
